CREATE TABLE IF NOT EXISTS service_jobs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  job_no VARCHAR(20) NULL UNIQUE,
  customer_name VARCHAR(100) NOT NULL,
  customer_phone VARCHAR(30) NULL,
  item_name VARCHAR(100) NOT NULL,
  karat VARCHAR(10) NULL,
  weight_gram DECIMAL(10,3) NOT NULL,
  complaint VARCHAR(255) NOT NULL,
  note VARCHAR(255) NULL,
  origin_location_id INT NOT NULL,
  location_id INT NOT NULL,
  pickup_location_id INT NULL,
  status ENUM('di_toko','dikirim_bo','di_bo','diproses','selesai','dikirim_toko','siap_diambil','diambil') NOT NULL DEFAULT 'di_toko',
  received_date DATE NOT NULL,
  sent_bo_date DATE NULL,
  arrived_bo_date DATE NULL,
  belum_sampai BOOLEAN NOT NULL DEFAULT FALSE,
  belum_sampai_note VARCHAR(255) NULL,
  service_name VARCHAR(100) NULL,
  service_start_date DATE NULL,
  service_end_date DATE NULL,
  weight_after DECIMAL(10,3) NULL,
  service_note VARCHAR(255) NULL,
  sent_toko_date DATE NULL,
  pickup_date DATE NULL,
  is_void BOOLEAN NOT NULL DEFAULT FALSE,
  void_reason VARCHAR(255) NULL,
  created_by INT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (origin_location_id) REFERENCES locations(id),
  FOREIGN KEY (location_id) REFERENCES locations(id),
  FOREIGN KEY (pickup_location_id) REFERENCES locations(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
);